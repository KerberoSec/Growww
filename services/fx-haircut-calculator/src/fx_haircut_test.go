func TestFXRateStalenessCheck(t *testing.T) {
	p := NewFXRateProvider(100 * time.Millisecond)
	_ = p.UpdateRate(FXRate{CurrencyUSD, CurrencyINR, 83.0, time.Now().Add(-1 * time.Second), "TEST"})

	_, err := p.GetRate(CurrencyUSD, CurrencyINR)
	if err == nil {
		t.Fatal("expected stale rate error")
	}
}

func TestFXRateIdentity(t *testing.T) {
	p := NewFXRateProvider(1 * time.Hour)
	rate, err := p.GetRate(CurrencyUSD, CurrencyUSD)
	if err != nil {
		t.Fatalf("unexpected error: %v", err)
	}
	if rate.Rate != 1.0 {
		t.Errorf("identity rate should be 1.0, got %f", rate.Rate)
	}
}

func TestFXRateInverseAutoGenerated(t *testing.T) {
	p := NewFXRateProvider(1 * time.Hour)
	_ = p.UpdateRate(FXRate{CurrencyUSD, CurrencyINR, 83.50, time.Now().UTC(), "TEST"})

	rate, err := p.GetRate(CurrencyINR, CurrencyUSD)
	if err != nil {
		t.Fatalf("inverse rate not found: %v", err)
	}
	expected := 1.0 / 83.50
	diff := rate.Rate - expected
	if diff < -0.0001 || diff > 0.0001 {
		t.Errorf("inverse rate %.8f != expected %.8f", rate.Rate, expected)
	}
}

